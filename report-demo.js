(() => {
  if (new URLSearchParams(location.search).get('scenario') !== 'low') return;
  const ar = document.documentElement.lang !== 'en';
  const text = (arabic, english) => ar ? arabic : english;
  document.querySelector('.summary').textContent = text('تقرير تجريبي يوضح سيناريو تنبيه انخفاض الضغط.', 'Demo report showing a low blood pressure alert scenario.');
  document.querySelector('.pressure-value').textContent = text('منخفض', 'Low');
  document.querySelector('.pressure-value').style.cssText = 'color:#a56416;font-size:22px';
  document.querySelector('.pressure-unit').textContent = text('سيناريو افتراضي', 'Simulated scenario');
  document.querySelector('.pressure-scale').hidden = true;
  document.querySelector('.pressure-scale').style.display = 'none';
  const dialog = document.createElement('dialog');
  dialog.setAttribute('aria-labelledby', 'alert-title');
  dialog.style.cssText = 'max-width:350px;width:90%;padding:27px;border:1px solid #f1dfc4;border-radius:24px;text-align:center;color:#4d463a';
  const title = document.createElement('h2'); title.id = 'alert-title';
  title.textContent = text('تنبيه: الضغط منخفض', 'Alert: low blood pressure');
  title.style.cssText = 'font-size:21px;color:#a26316;margin:0 0 15px';
  const description = document.createElement('p');
  description.textContent = text('خذ استراحة قصيرة واجلس بهدوء، ثم أعد القياس قبل إكمال النشاط.', 'Take a short break and sit quietly, then measure again before continuing activity.');
  const note = document.createElement('p');
  note.textContent = text('تنبيه تمثيلي للديمو فقط، وليس مبنيًا على قياس فعلي. المتابعة لا تعني أن الضغط عاد إلى الطبيعي.', 'Demo alert only, not based on a real reading. Continuing does not mean blood pressure has returned to normal.');
  note.style.cssText = 'font-size:12px;color:#7c776e;line-height:1.7';
  const close = document.createElement('button');
  close.textContent = text('حسنًا، عرض التقرير', 'OK, view report');
  close.onclick = () => dialog.close();
  dialog.append(title, description, note, close); document.body.append(dialog);
  const reminder = document.createElement('button');
  reminder.textContent = text('عرض تنبيه الضغط التجريبي', 'Show demo pressure alert');
  reminder.style.cssText = 'display:block;margin:16px auto 0;border:1px solid #e9cfa8;background:#fff8ec;border-radius:16px;padding:10px 16px;color:#8e5a16;font:inherit;cursor:pointer';
  reminder.onclick = () => dialog.showModal();
  document.querySelector('.demo-note').after(reminder);
  const next = document.querySelector('#recommendations');
  next.querySelector('span').textContent = text('إعادة القياس', 'Measure again');
  next.onclick = () => { location.href = 'checkup.html?lang=' + (ar ? 'ar' : 'en'); };
  dialog.showModal();
})();
